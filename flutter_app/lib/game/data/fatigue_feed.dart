/// 게임이 바라보는 신호 인터페이스.
///
/// ## 이 게임은 스킬 게임이 아니다
///
/// 대상은 완전마비 환자다. 근수축을 만드는 것은 FES(전기자극)이고, 환자가
/// 타이밍을 맞히거나 더 세게 쥘 방법은 없다. 그래서 판정창·점수·콤보가 없다.
///
/// **성공 지표는 "수축이 일어났다는 사실" 그 자체**다. 자기 근육이 수축했고
/// 그것이 공을 잡는 장면으로 되돌아오는 것 — 그 되먹임이 신경가소성을 노리는
/// 이 화면의 목적이다.
///
/// ## 힘의 크기는 쓰지 않는다
///
/// [ContractionEvent] 에 진폭이 없는 것은 의도다. 완전마비에서는 힘의 세기를
/// 환자 능력으로 해석할 수 없고, 근피로는 힘 크기와 무관하게 M-wave(자극 후
/// 5~15ms 유발응답)의 SPC σ 편차로 판별한다. 게임에는 **타이밍만** 쓴다.
library;

/// 전형적인 자극 지속시간(초). 실측 세션 379버스트 중앙값.
///
/// 주기 1.618초 = 자극 0.629초 + 쉼 0.99초. "수축이 1.6초 내내" 가 아니다.
const double kTypicalContractionSec = 0.629;

/// M-wave 에서 검출된 근수축 1회.
///
/// 진폭·면적을 일부러 담지 않는다 — 위 설명 참고.
class ContractionEvent {
  const ContractionEvent(this.t, {this.holdSec = kTypicalContractionSec});

  /// 수축이 시작된 시각(초).
  final double t;

  /// 수축이 **유지되는** 시간(초).
  ///
  /// FES 는 버스트마다 ≈31ms 간격 펄스 train 을 쏘고 근육은 그동안 수축한다.
  /// 실측 포락선(0~620ms 자극 / 620~1600ms 쉼)에서 **중앙 0.629초**,
  /// 주기 1.618초의 약 39% 다. 나머지 1초는 쉼 구간이다.
  ///
  /// 포구도 순간이 아니라 이만큼 **잡고 있는** 상태여야 한다 — 근육이 수축하는
  /// 동안 공을 쥐고 있는 것이 되먹임의 내용이기 때문이다.
  final double holdSec;

  /// 수축이 끝나는 시각(초).
  double get endT => t + holdSec;
}

/// 피로·수축 신호원. 목(재생)과 실측이 같은 인터페이스를 쓴다.
abstract class FatigueFeed {
  /// M-wave 로 검출된 수축 이벤트.
  Stream<ContractionEvent> get contractions;

  /// 현재 SPC σ — 초기 baseline 대비 편차. 인과적·실시간.
  ///
  /// 1차 피로 라벨이다. 학습 데이터가 없어도, 새 피험자 첫 세션에도 동작한다.
  Stream<double> get sigmaNow;

  /// LSTM 이 예측한 N초 후 σ — 선제 경고용.
  ///
  /// [sigmaNow] 가 사후 확인이라면 이쪽은 예고다. 게이지에 겹쳐 표시한다.
  Stream<double> get sigmaPredicted;

  /// 예측이 내다보는 시간(초).
  double get predictionHorizonSec;

  /// ★ 이 피드의 현재 시각(초). **게임의 유일한 시계다.**
  ///
  /// 게임이 따로 `dt` 를 누적하면 안 된다. 재생 피드는 배속이 걸려 세션 시간이
  /// 실시간보다 빠르게 흐르는데, 두 시계가 갈라지면 공의 출발·도착 계산이
  /// 통째로 어긋난다(공이 아예 안 나오거나 순간이동한다).
  double get nowSec;

  /// 다음 수축이 올 것으로 보는 시각(초). 모르면 null.
  ///
  /// 공은 원경에서 날아오는 데 시간이 걸리므로, **도착 시각을 미리 알아야**
  /// 그만큼 앞서 던질 수 있다. FES 주기는 실측 1618ms 로 잠겨 있어(min 1615,
  /// max 1622) 직전 수축 + 주기로 충분히 정확하다. 예측이 어긋나면 실제 수축이
  /// 온 순간에 포구가 일어나고 공이 그 시점으로 스냅한다.
  double? get nextContractionEta;

  Future<void> start();
  Future<void> stop();
  void dispose();
}
